// node receipt.test.cjs — self-contained event-shape checks.
const assert = require('node:assert/strict');
const {summarizeEvents, shareReceipt} = require('./receipt.js');
const encode = events => events.map(e => JSON.stringify(e)).join('\n');
const started = {type:'item.started',item:{id:'cmd_1',type:'command_execution',command:'python3 test_example.py',exit_code:null,status:'in_progress'}};
const completed = {type:'item.completed',item:{id:'cmd_1',type:'command_execution',command:'python3 test_example.py',aggregated_output:'PASS',exit_code:0,status:'completed'}};
const turn = {type:'turn.completed',usage:{input_tokens:100,cached_input_tokens:50,output_tokens:10}};
const summary = summarizeEvents(encode([started,completed,{type:'item.completed',item:{type:'agent_message',text:'Tests passed.'}},turn]));
assert.equal(summary.status,'completed');
assert.deepEqual(summary.commands,{total:1,exit_zero:1,exit_nonzero:0,unfinished:0});
assert.equal(summary.usage.cached_input_tokens,50);
assert.equal(summary.details.final_answer,'Tests passed.');
const shared=shareReceipt(summary,{codex_exit:0,model:'example-model',api_key:'secret-sentinel'});
assert.ok(!JSON.stringify(shared).includes('test_example.py'));
assert.ok(!JSON.stringify(shared).includes('secret-sentinel'));
assert.equal(summarizeEvents(encode([started])).status,'incomplete');
assert.equal(summarizeEvents(encode([started])).commands.unfinished,1);
assert.equal(summarizeEvents(encode([started,{type:'turn.failed',error:{message:'401'}}])).status,'failed');
const nonzero = summarizeEvents('\uFEFF'+encode([started,{...completed,item:{...completed.item,exit_code:1}},turn])+'\nbroken');
assert.equal(nonzero.status,'completed');
assert.equal(nonzero.commands.exit_nonzero,1);
assert.equal(nonzero.malformed_lines,1);
// Repeated/cumulative snapshots are not independent per-turn charges.
const laterTurn = {type:'turn.completed',usage:{input_tokens:180,cached_input_tokens:120,cache_write_input_tokens:0,output_tokens:20,reasoning_output_tokens:7}};
assert.equal(summarizeEvents(encode([turn,turn])).usage.input_tokens,100);
const cumulative = summarizeEvents(encode([turn,laterTurn]));
assert.deepEqual(cumulative.usage,laterTurn.usage);
assert.equal(cumulative.completed_turns,2);
assert.equal(cumulative.schema_version,2);
assert.equal(shareReceipt(cumulative).usage_basis,'latest_reported_thread_total');
assert.deepEqual(summarizeEvents(encode([laterTurn,{type:'turn.completed',usage:{input_tokens:0,output_tokens:0}}])).usage,{input_tokens:0,output_tokens:0});
// Native non-fatal ErrorItem was observed during a blocked 0.171.0 tool-host startup.
const message = 'Code Mode unavailable: host executable was not found.';
const itemError = {type:'item.completed',item:{id:'item_0',type:'error',message}};
const blocked = summarizeEvents(encode([itemError,{type:'item.completed',item:{type:'agent_message',text:'The test command did not run.'}},turn]));
assert.equal(blocked.status,'completed');
assert.equal(blocked.commands.total,0);
assert.deepEqual(blocked.details.errors,[message]);
assert.equal(blocked.details.final_answer,'The test command did not run.');
assert.ok(!JSON.stringify(shareReceipt(blocked)).includes(message));
console.log('PASS: completion, command exits, latest cumulative usage, summary fields, partial/failed runs, BOM, native messages');
