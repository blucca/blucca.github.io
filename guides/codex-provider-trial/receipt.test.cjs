const assert = require('node:assert/strict');
const fs = require('node:fs');
const {summarizeEvents, shareReceipt} = require('./receipt.js');
const native = summarizeEvents(fs.readFileSync('.private/native-acquisition/events.jsonl', 'utf8'));
assert.equal(native.status, 'completed');
assert.equal(native.commands.total, 5);
assert.equal(native.commands.exit_zero, 5);
assert.equal(native.commands.unfinished, 0);
assert.ok(native.details.commands.some(c => c.command.includes('python3 test_dedupe.py') && c.exit_code === 0 && c.aggregated_output.includes('PASS')));
assert.ok(native.usage.input_tokens > 0 && native.usage.cached_input_tokens >= 0);
assert.ok(native.details.final_answer);
const raw = JSON.stringify(native.details);
const shared = JSON.stringify(shareReceipt(native, {codex_exit:0, api_key:'sentinel-secret',model:'test-model'}));
assert.ok(!shared.includes('sentinel-secret') && !shared.includes('dedupe.py'));
assert.ok(!shared.includes('details') && raw.includes('dedupe.py'));
const encode = events => events.map(e => JSON.stringify(e)).join('\n');
const start = {type:'item.started',item:{id:'1',type:'command_execution',exit_code:null,status:'in_progress'}};
assert.equal(summarizeEvents(encode([start])).status,'incomplete');
assert.equal(summarizeEvents(encode([start])).commands.unfinished,1);
assert.equal(summarizeEvents(encode([start,{type:'turn.failed',error:{message:'401'}}])).status,'failed');
assert.deepEqual(summarizeEvents(encode([{type:'turn.completed',usage:{input_tokens:5}},{type:'turn.completed',usage:{input_tokens:7}}])).usage,{input_tokens:12});
const nonzero = summarizeEvents('\uFEFF'+encode([start,{type:'item.completed',item:{id:'1',type:'command_execution',exit_code:1}},{type:'turn.completed'}])+'\nbroken');
assert.equal(nonzero.commands.exit_nonzero,1);
assert.equal(nonzero.status,'completed');
assert.equal(nonzero.malformed_lines,1);
console.log(JSON.stringify({actual_native_run:'pass',deduplicated_command_exits:'pass',actual_test_output:'pass',private_fields_omitted:'pass',partial_failed_nonzero_bom:'pass',multi_turn_usage:'pass'}));
